/**
 * Writes the codicon `:before` rules the ADE's renderer needs.
 *
 * The fork ships the font and a base stylesheet, but not one line of
 * `.codicon-x:before { content: "\e123" }` — it builds those at runtime from
 * `getCodiconFontCharacters()` through the theme service's `iconsStyleSheet.ts`.
 * The ADE's renderer has no theme service, so the same rules are generated here,
 * ahead of time, from the same source of truth.
 *
 * Every rule is scoped under `.agent-sessions-workbench`. The ADE's renderer
 * already carries Monaco's copy of this font, and an unscoped `.codicon-x` rule
 * here would reach Monaco's elements too.
 *
 * Generated rather than hand-written because hand-copying codepoints is exactly
 * the kind of transcription that goes wrong silently — a wrong glyph still
 * renders. Re-run after pulling a new codicon font:
 *
 *     node build/kingu-orca/generate-codicon-css.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const forkRoot = join(here, '..', '..')
const library = join(forkRoot, 'src', 'vs', 'base', 'common', 'codiconsLibrary.ts')
const out = join(
  forkRoot,
  'kingu-orca',
  'renderer',
  'src',
  'app-shell',
  'agents-titlebar',
  'codicons',
  'codicons.generated.css'
)

const source = readFileSync(library, 'utf8')
// `spinner: register('loading', 0xeb19),` — the kebab id is what lands in the
// class name, and the codepoint is what the font maps.
const entries = [...source.matchAll(/register\('([a-z0-9-]+)',\s*(0x[0-9a-fA-F]+)\)/g)]
if (entries.length === 0) {
  throw new Error(`no codicons found in ${library} — did its format change?`)
}

const rules = entries
  .map(([, id, codepoint]) => '.agent-sessions-workbench .codicon-' + id + ':before { content: "\\' + Number(codepoint).toString(16).padStart(4, '0') + '"; }')
  .join('\n')

writeFileSync(
  out,
  `/* Generated by build/kingu-orca/generate-codicon-css.mjs — do not edit.\n` +
    `   ${entries.length} icons from src/vs/base/common/codiconsLibrary.ts. */\n\n` +
    `${rules}\n`,
  'utf8'
)
console.log(`wrote ${entries.length} codicon rules to ${out}`)
