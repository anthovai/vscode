/**
 * Writes the lucide icons the ADE's footer draws as data the Agents Window's
 * footer can build SVG from.
 *
 * Generated from the ADE's own copy of lucide-react (`kingu-orca/node_modules`),
 * not redrawn: a hand-copied path that is off by one control point still draws
 * an icon, and would never look like a bug. Lucide is ISC-licensed.
 *
 * Run: node build/kingu-orca/generate-lucide-icons.mjs
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '../..');
const iconsDir = path.join(root, 'kingu-orca/node_modules/lucide-react/dist/esm/icons');
const outFile = path.join(root, 'src/vs/sessions/contrib/kingu/common/kinguLucideIcons.ts');

/** Every icon the ADE's status bar, its popovers and its settings screen import. */
const ICONS = ['coffee', 'memory-stick', 'terminal', 'plug', 'panels-top-left', 'refresh-cw', 'triangle-alert', 'circle-alert', 'circle-check', 'download', 'loader-circle', 'server', 'server-off', 'monitor-smartphone', 'rotate-cw', 'trash-2', 'x', 'chevron-down', 'chevron-right', 'external-link', 'copy', 'folder-open', 'circle', 'bot', 'user-cog', 'network', 'mouse-pointer-click', 'mic', 'circle-user-round', 'sliders-horizontal', 'blocks', 'smartphone', 'calendar-clock', 'files', 'book-open', 'history', 'git-branch', 'list-checks', 'square-terminal', 'play', 'globe', 'tablet-smartphone', 'palette', 'text-cursor-input', 'bell', 'keyboard', 'chart-column', 'cable', 'shield-check', 'lock', 'wrench', 'bug', 'flask-conical', 'arrow-left', 'search', 'hard-drive', 'check', 'plus', 'maximize-2', 'minimize-2', 'minus', 'file-text', 'github', 'gitlab', 'arrow-up', 'arrow-down', 'arrow-right', 'circle-dot', 'git-pull-request', 'git-pull-request-draft', 'chevrons-up-down', 'chevron-left'];

const out = {};
for (const name of ICONS) {
	const source = fs.readFileSync(path.join(iconsDir, `${name}.js`), 'utf8');
	const body = source.slice(source.indexOf('__iconNode = ['), source.indexOf('];', source.indexOf('__iconNode = [')) + 2);
	const elements = [];
	for (const match of body.matchAll(/"(?<tag>path|rect|circle|line|polyline|polygon|ellipse)",\s*\{(?<attrs>[^}]*)\}/g)) {
		const attrs = {};
		for (const attr of match.groups.attrs.matchAll(/(?<key>\w+):\s*"(?<value>[^"]*)"/g)) {
			if (attr.groups.key !== 'key') {
				attrs[attr.groups.key] = attr.groups.value;
			}
		}
		elements.push([match.groups.tag, attrs]);
	}
	if (elements.length === 0) {
		throw new Error(`no shapes read for ${name}`);
	}
	out[name] = elements;
}

const lines = [
	'/*---------------------------------------------------------------------------------------------',
	' *  Kingu Intelligence',
	' *  Licensed under the MIT License.',
	' *--------------------------------------------------------------------------------------------*/',
	'',
	'// GENERATED by build/kingu-orca/generate-lucide-icons.mjs from the ADE\'s lucide-react',
	'// (ISC license). Do not edit; run the generator again.',
	'',
	'/** One SVG element of a lucide icon: its tag and attributes, drawn on a 24 x 24 stroke grid. */',
	'export type KinguLucideElement = readonly [string, Readonly<Record<string, string>>];',
	'',
	'/** The icons the ADE\'s footer draws, by lucide name. */',
	'export const KINGU_LUCIDE_ICONS: Readonly<Record<string, readonly KinguLucideElement[]>> = {',
	...Object.entries(out).map(([name, elements]) => `\t'${name}': ${JSON.stringify(elements).replace(/"/g, '\'')},`),
	'};',
	'',
];
fs.writeFileSync(outFile, lines.join('\n'));
console.log(`kingu-orca: ${Object.keys(out).length} lucide icons -> ${path.relative(root, outFile)}`);
